/* entries hold the macOS code + 1 so that 0 means "no such key" (the A key is code 0) */
int ws_input_mac_keycode(int c) { if (c < 0 || c > 255 || !keymap[c]) return -1; return keymap[c] - 1; }

/* inverse of the table above: evdev code for a macOS virtual key code, -1 when none */
int ws_input_evdev_code(int mac) { for (int c = 0; c < 256; c++) if (keymap[c] && keymap[c] - 1 == mac) return c; return -1; }
