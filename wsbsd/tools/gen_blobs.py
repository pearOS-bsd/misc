#!/usr/bin/env python3
"""Generates src/sls_blobs.c: the binary property lists wsd answers CopyManagedDisplays (30389) and GetDevices (30456) with. Same shape as the real server's replies
(recorded on the macOS runner); the display UUID and the device list describe wsd's own display and input devices."""
import plistlib,sys
UUID='5E1D1A5B-0C3E-4D5B-9D2A-6F57A5B0C0DE'
displays=plistlib.dumps([UUID],fmt=plistlib.FMT_BINARY)
kb=0x100000a01; ms=0x100000a02
def dev(cls,prod,usage,page,vid,pid,loc,rid,sub=None):
    d={'IOClass':cls,'VendorID':vid,'CountryCode':0,'Product':prod,'PrimaryUsage':usage,'LocationID':loc,'DeviceUsagePairs':[{'DeviceUsagePage':page,'DeviceUsage':usage}],
       'ProductID':pid,'Transport':'USB','IORegistryEntryID':rid,'Manufacturer':'wsbsd','PrimaryUsagePage':page,'SLDeviceUsages':{str(page):[usage]}}
    if sub: d['HIDSubinterfaceID']=sub
    return d
devices=plistlib.dumps({'SLBuiltInDeviceIDs':[],'SLKeyboardDeviceIDs':[kb],'SLTrackpadDeviceIDs':[],'SLGestureScrollDeviceIDs':[],'SLDefaultKeyboardID':198,
  'SLGestureScrollTrackpadDeviceIDs':[],'SLMouseDeviceIDs':[ms],'SLTouchBarDeviceIDs':[],'SLSidecarDeviceIDs':[],'SLBuiltInMultitouchDeviceIDs':[],
  'SLDeviceDictionaries':{str(kb):dev('wsbsdKeyboard','wsbsd Keyboard',6,1,1452,33029,0x0c800000,kb,198),str(ms):dev('wsbsdPointer','wsbsd Pointer',2,1,1452,33030,0x0c900000,ms)}},fmt=plistlib.FMT_BINARY)
def arr(n,b): return 'const uint8_t %s[] = {%s};\nconst unsigned %s_len = %d;\n'%(n,','.join(str(x) for x in b),n,len(b))
open(sys.argv[1],'w').write('/* Generated by tools/gen_blobs.py -- do not edit. */\n#include <stdint.h>\n'+arr('sls_blob_displays',displays)+arr('sls_blob_devices',devices))
print(len(displays),len(devices))
