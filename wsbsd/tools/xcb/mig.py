#!/usr/bin/env python3
"""A stand-in for Mach's `mig` on a system without Mach IPC: reads a .defs subsystem and writes the client header Xcode's MIG rule would, with every routine
returning KERN_FAILURE (there is no Mach port to send the message to). Programs that only use the routines when a privileged helper is available keep working
without it. usage: mig.py FILE.defs OUTDIR  ->  OUTDIR/<name>.h"""
import os, re, sys

BUILTIN = {"int": "int", "int32_t": "int32_t", "uint32_t": "uint32_t", "uint64_t": "uint64_t", "int64_t": "int64_t", "uint8_t": "uint8_t", "int8_t": "int8_t",
           "mach_port_t": "mach_port_t", "boolean_t": "int", "natural_t": "unsigned int", "integer_t": "int", "pointer_t": "void *", "kern_return_t": "kern_return_t"}

def parse(text):
    text = re.sub(r"//.*", "", text); text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    types = {}
    for m in re.finditer(r"type\s+(\w+)\s*=\s*([^;]+);", text):
        name, body = m.group(1), m.group(2).strip()
        if re.match(r"c_string\[\*?:?(\d+)\]", body): types[name] = ("cstr", int(re.search(r"(\d+)", body).group(1)))
        elif body.startswith("^"):
            e = re.search(r"of\s+(\w+)", body); types[name] = ("ool", e.group(1) if e else "uint8_t")
        elif body.startswith("struct"):
            n = re.search(r"\[(\d+)\]\s*of\s+(\w+)", body); types[name] = ("arr", int(n.group(1)), n.group(2))
        elif body.startswith("array"):
            e = re.search(r"\[[^\]]*\]\s*of\s+(\w+)", body); types[name] = ("inl", e.group(1) if e else "uint8_t")
        elif body.startswith("MACH_MSG_TYPE"): types[name] = ("port",)
        else: types[name] = ("alias", body.split()[0])
    prefix = (re.search(r"userprefix\s+(\w+)", text) or [None, ""])[1]
    sub = (re.search(r"subsystem\s+(\w+)", text) or [None, "subsystem"])[1]
    routines = []
    for m in re.finditer(r"(simpleroutine|routine)\s+(\w+)\s*\((.*?)\)\s*;", text, flags=re.S):
        params = []
        for p in m.group(3).split(";"):
            p = p.strip()
            if not p: continue
            d = re.match(r"(?:(in|out|inout|requestport|replyport|sreplyport|msgoption|waittime)\s+)?(\w+)\s*:\s*([\w\s\[\]\*\^:]+?)(?:\s*,\s*[^;]*)?$", p)
            if d: params.append((d.group(1) or "in", d.group(2), d.group(3).strip()))
        routines.append((m.group(2), params))
    return sub, prefix, types, routines

def ctype(t, types):
    k = types.get(t)
    if not k: return BUILTIN.get(t, t)
    if k[0] == "port": return "mach_port_t"
    if k[0] == "alias": return ctype(k[1], types)
    return t

def main(a):
    src, out = a[0], a[1]
    sub, prefix, types, routines = parse(open(src, encoding="utf-8", errors="replace").read())
    os.makedirs(out, exist_ok=True)
    name = os.path.splitext(os.path.basename(src))[0]
    L = ["/* generated by tools/xcb/mig.py from %s: client stubs that report KERN_FAILURE (no Mach IPC) */" % os.path.basename(src), "#ifndef _%s_user_" % name,
         "#define _%s_user_" % name, "#include <stdint.h>", "#include <mach/mach.h>", "#include <mach/message.h>"]
    for m in re.finditer(r'^\s*import\s+"([^"]+)"', open(src, encoding="utf-8", errors="replace").read(), flags=re.M): L.append('#include "%s"' % m.group(1))
    imported = ""
    for m in re.finditer(r'^\s*import\s+"([^"]+)"', open(src, encoding="utf-8", errors="replace").read(), flags=re.M):
        f = os.path.join(os.path.dirname(os.path.abspath(src)), m.group(1))
        if os.path.exists(f): imported += open(f, encoding="utf-8", errors="replace").read()
    for t, k in types.items():
        if t == "AuthorizationExternalForm" or re.search(r"\b%s\b" % re.escape(t), imported): continue                  # the interface's own headers already define it
        if k[0] == "cstr": L.append("typedef char %s[%d];" % (t, k[1]))
        elif k[0] == "ool" or k[0] == "inl": L.append("typedef %s *%s;" % (BUILTIN.get(k[1], k[1]), t))
        elif k[0] == "arr": L.append("typedef %s %s[%d];" % (BUILTIN.get(k[2], k[2]), t, k[1]))
        elif k[0] == "port": L.append("typedef mach_port_t %s;" % t)
        elif k[0] == "alias" and k[1] != t and t not in ("bool", "int", "boolean_t"): L.append("typedef %s %s;" % (ctype(k[1], types), t))
    for rname, params in routines:
        args = []
        for d, n, t in params:
            k = types.get(t); c = ctype(t, types) if not re.match(r"c_string|array|\^", t) else t
            if d in ("out", "inout"):
                if k and k[0] == "ool": args += ["%s *%s" % (t, n), "mach_msg_type_number_t *%sCnt" % n]
                elif k and k[0] in ("cstr", "arr"): args.append("%s %s" % (t, n))
                else: args.append("%s *%s" % (c, n))
            elif k and k[0] == "ool": args += ["%s %s" % (t, n), "mach_msg_type_number_t %sCnt" % n]
            elif k and k[0] in ("cstr", "arr"): args.append("%s %s" % (t, n))
            else: args.append("%s %s" % (c, n))
        L.append("static inline kern_return_t %s%s(%s) { return KERN_FAILURE; }" % (prefix, rname, ", ".join(args) if args else "void"))
    L.append("#endif")
    open(os.path.join(out, name + ".h"), "w").write("\n".join(L) + "\n")
    print("mig stand-in: %d routines of %s -> %s.h" % (len(routines), name, name))

if __name__ == "__main__": main(sys.argv[1:])
