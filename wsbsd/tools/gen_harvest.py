#!/usr/bin/env python3
"""Turns docs/golden/harvest-*.txt (replies of the real WindowServer to fixed-size requests with zero / window / connection arguments) into src/sls_harvest.c:
the default answer of wsd for a routine that has no dedicated handler yet. variant 0: all arguments zero; 1: first argument a window owned by the caller; 2: first argument the
caller's connection id. Only success shapes recorded in a fresh session: this is a placeholder with the right sizes and error codes, to be replaced by real behaviour."""
import re,sys,collections
recs=collections.defaultdict(dict)
for l in (ln for path in sys.argv[2:] for ln in open(path)):
    m=re.match(r'id=(\d+) variant=(\d) reqsize=(\d+) reply_id=(\d+) bits=([0-9a-f]+) size=(\d+) hex=([0-9a-f?]*)',l)
    if not m: continue
    i,v,rq,rid,bits,size,hx=int(m[1]),int(m[2]),int(m[3]),int(m[4]),int(m[5],16),int(m[6]),m[7]
    if hx=='?' or size>0x100: continue
    if size==0x24 and hx[16:24]=='d1feffff': continue                  # -303: the routine is served on another port
    recs[i][v]=(rq,rid,bits,size,bytes.fromhex(hx))
out=['/* Generated by tools/gen_harvest.py from the files in docs/golden -- do not edit. */','#include "wsd_priv.h"','#include <string.h>','',
     'typedef struct { uint32_t size, body_len; int complex; const uint8_t *body; } hv_reply;',
     'typedef struct { int id; uint32_t req_size; hv_reply v[3]; int have[3]; } hv_entry;']
for i,vs in sorted(recs.items()):
    for v,(rq,rid,bits,size,b) in vs.items():
        out.append('static const uint8_t h%d_%d[] = {%s};'%(i,v,','.join(str(x) for x in b) if b else '0'))
out.append('static const hv_entry harvest[] = {')
for i,vs in sorted(recs.items()):
    rq=next(iter(vs.values()))[0]
    parts=[];have=[]
    for v in range(3):
        if v in vs:
            _,_,bits,size,b=vs[v]; parts.append('{ %d, %d, %d, h%d_%d }'%(size,len(b),int(bool(bits&0x80000000)),i,v)); have.append('1')
        else: parts.append('{ 0, 0, 0, 0 }'); have.append('0')
    out.append('\t{ %d, %d, { %s }, { %s } },'%(i,rq,', '.join(parts),', '.join(have)))
out.append('};')
out.append('''
/* Default answer for a fixed-size request: size is checked as the real routine does (-304), then the recorded reply for the argument class. Returns -2 if unknown. */
int sls_harvest_reply(conn *c, const uint8_t *buf, size_t len)
{
	const mach_msg_header_t *h = (const mach_msg_header_t *)buf;
	for (size_t i = 0; i < sizeof harvest / sizeof harvest[0]; i++) {
		if (harvest[i].id != h->msgh_id) continue;
		if ((h->msgh_bits & MACH_MSGH_BITS_COMPLEX) || h->msgh_size != harvest[i].req_size || len != h->msgh_size) return reply_simple(c->fd, h, -304);
		int variant = 0;
		if (len >= 0x24) {
			uint32_t a = rd32(buf, 0x20);
			if (a && a == c->id && harvest[i].have[2]) variant = 2;
			else if (a && holds_rights(c, a) && harvest[i].have[1]) variant = 1;
		}
		if (!harvest[i].have[variant]) variant = harvest[i].have[0] ? 0 : (harvest[i].have[1] ? 1 : 2);
		const hv_reply *r = &harvest[i].v[variant];
		uint8_t m[0x120]; memset(m, 0, sizeof m);
		fill_reply_header((mach_msg_header_t *)m, h, r->size, r->complex);
		memcpy(m + 0x18, r->body, r->body_len);
		static const uint8_t zeros[0x1000];
		uint32_t osz = r->complex && r->size >= 0x2c && m[0x27] == 1 ? rd32(m, 0x28) : 0;            /* an out-of-line payload the recording does not hold: zero bytes of the announced size follow */
		if (osz > sizeof zeros) osz = sizeof zeros;
		struct iovec v[2] = { { m, r->size }, { (void *)zeros, osz } };
		return ws_ipc_send(c->fd, v, osz ? 2 : 1, NULL, 0);
	}
	return -2;
}''')
open(sys.argv[1],'w').write('\n'.join(out)+'\n')
print(len(recs),'routines')
