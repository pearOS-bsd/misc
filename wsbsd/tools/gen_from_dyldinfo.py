#!/usr/bin/env python3
"""gen_from_dyldinfo.py DYLD_INFO_OBJC.txt OUT.mm [--prefix-skip FILE]: turns the output of `dyld_info -objc BINARY` (classes, categories, methods with their addresses) into a compilable
Objective-C++ skeleton: every class with its superclass and every method as a stub that returns nil/0 and carries the address of the original in a comment ("/* 0x10011B050 */"), the worklist of the
decompilation. Types are unknown in this format: everything is `id`. Classes whose superclass is not defined here and not an AppKit/Foundation class are rooted at NSObject.
Methods defined in hand-written files (`@implementation X (Impl)` blocks, see tools/impl_skips.py) are skipped through --skip FILE (lines "-Class selector")."""
import re, sys, collections
src, out = sys.argv[1], sys.argv[2]
skip = set()
if "--skip" in sys.argv:
    for l in open(sys.argv[sys.argv.index("--skip") + 1]):
        l = l.strip()
        if l: skip.add(l)
SYSSEL = {}      # system class -> the selectors it implements (inherited ones included): a stub would override real behaviour with nil, so those are not generated
if "--system-selectors" in sys.argv:
    for l in open(sys.argv[sys.argv.index("--system-selectors") + 1]):
        n_, _, r_ = l.rstrip("\n").partition("\t")
        if r_ and r_ != "?": SYSSEL[n_] = set(r_.split(" "))
KNOWN_SYSTEM = set()
if "--system-classes" in sys.argv:
    KNOWN_SYSTEM = set(l.strip() for l in open(sys.argv[sys.argv.index("--system-classes") + 1]) if l.strip())
import os
handdir = sys.argv[sys.argv.index("--hand-dir") + 1] if "--hand-dir" in sys.argv else None   # classes written by hand (DIR/Class.mm) are not generated
classes = collections.OrderedDict(); cats = []; cur = None
for l in open(src, errors="replace"):
    m = re.match(r"\s+@interface (\S+) \((\w+)\)", l)
    if m: cur = {"name": m.group(1), "cat": m.group(2), "methods": []}; cats.append(cur); continue
    m = re.match(r"\s+@interface (\S+)(?: : (\S+))?(?: <([^>]*)>)?", l)
    if m: cur = {"name": m.group(1), "super": m.group(2), "protos": m.group(3), "methods": []}; classes[m.group(1)] = cur; continue
    m = re.match(r"\s+(0x[0-9A-Fa-f]+)\s+([-+])\[(\S+?)(?: \(\w+\))? (\S+)\]", l)
    if m and cur: cur["methods"].append((m.group(1), m.group(2), m.group(4)))
def bad(n): return not re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", n) or "." in n
order = []; seen = set()
def visit(n):
    if n in seen or n not in classes: return
    seen.add(n); s = classes[n]["super"]
    if s in classes: visit(s)
    order.append(n)
for n in classes: visit(n)
def nearest(s):
    """an AppKit class that does not exist here (NSSplitViewItemAccessoryViewController ...): the closest one by its name"""
    for suf, base in (("ViewController", "NSViewController"), ("WindowController", "NSWindowController"), ("TableView", "NSTableView"), ("CollectionView", "NSCollectionView"), ("ToolbarItem", "NSToolbarItem"), ("ImageRep", "NSImageRep"), ("Cell", "NSCell"), ("View", "NSView"), ("Control", "NSControl"), ("Controller", "NSObject")):
        if s and s.endswith(suf) and base in KNOWN_SYSTEM: return base
    return "NSObject"
FAM = " __attribute__((objc_method_family(none)))"
def sel_decl(sel):
    if ":" not in sel: return sel, 0
    parts = sel.split(":")[:-1]; return " ".join("%s:(id)a%d" % (p, i) for i, p in enumerate(parts)), len(parts)
O = ['/* generated by tools/gen_from_dyldinfo.py from %s: do not edit; implement in hand-written files */' % src, "#import <AppKit/AppKit.h>", "#import <QuartzCore/QuartzCore.h>", ""]
handnames = set()
if handdir:
    for f_ in os.listdir(handdir):
        if f_.endswith((".mm", ".m")) and not f_.endswith("_Generated.mm"):
            for l_ in open(os.path.join(handdir, f_), errors="replace"):
                m_ = re.match(r"@implementation (\w+)\s*$", l_)
                if m_: handnames.add(m_.group(1))
hand = set(n for n in order if n in handnames or (handdir and (os.path.exists(os.path.join(handdir, n + ".mm")) or os.path.exists(os.path.join(handdir, n + ".m")))))
good = [n for n in order if not bad(n) and n not in hand]
def declared(n): return n in classes and not bad(n)
for n in sorted(hand): O.append('#import "%s.h"' % n) if os.path.exists(os.path.join(handdir, n + ".h")) else None
for n in good:
    s = classes[n]["super"]; sup = s if (s in classes and not bad(s)) or s in KNOWN_SYSTEM or (not KNOWN_SYSTEM and s and s.startswith("NS")) else nearest(s)
    O.append("@interface %s : %s @end" % (n, sup))
O.append("")
nstub = 0
for n in good:
    O.append("@implementation %s" % n)
    seen_sel = set(); anc = classes[n]["super"]
    while anc in classes: anc = classes[anc]["super"]
    inherited = SYSSEL.get(anc, set())
    for addr, sign, sel in classes[n]["methods"]:
        if bad(sel.replace(":", "")) or sel in ("dealloc", "retain", "release", "autorelease", "retainCount", "finalize") or sel.startswith(".cxx") or (sign + n + " " + sel) in skip or (sign, sel) in seen_sel or (sign + sel) in inherited: continue
        seen_sel.add((sign, sel)); d, k = sel_decl(sel)
        if sel.startswith("set") and k == 1 and False: pass
        O.append("%s (id)%s%s { /* %s */ return nil; }" % (sign, d, FAM if sel in ("copy:", "mutableCopy:") else "", addr)); nstub += 1
    O.append("@end")
for c in cats:
    if bad(c["name"]) or bad(c["cat"]) or c["name"] not in seen and not KNOWN_SYSTEM and not c["name"].startswith("NS"): continue
    O.append("@implementation %s (%s)" % (c["name"], c["cat"])); ss = set()
    for addr, sign, sel in c["methods"]:
        if bad(sel.replace(":", "")) or (sign, sel) in ss: continue
        ss.add((sign, sel)); d, k = sel_decl(sel); O.append("%s (id)%s%s { /* %s */ return nil; }" % (sign, d, FAM if sel in ("copy:", "mutableCopy:") else "", addr)); nstub += 1
    O.append("@end")
open(out, "w").write("\n".join(O) + "\n")
print("%d classes, %d categories, %d stub methods" % (len(good), len(cats), nstub))
