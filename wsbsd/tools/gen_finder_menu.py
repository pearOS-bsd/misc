#!/usr/bin/env python3
"""Makes finder/src/TMenuFallback.inc: the Finder's menu bar as a table (depth, title, action, key, modifier mask), used when the bundle has no MenuBar nib (the nib is a resource of the Mac's Finder and is not shipped).
Structure and actions: docs/desktop/Finder.menu-actions.txt (FINDER_DUMPMENU=1 on the nib's menu); keys and modifiers: docs/desktop/Finder.menu-ax-dump.tsv (the accessibility tree of the running Finder: AXMenuItemCmdChar / AXMenuItemCmdModifiers, bit 1 shift, 2 option, 4 control, 8 no command key).
The items that exist only as hidden alternates (not in the accessibility tree) get the option key."""
import re, sys, collections
root = sys.argv[1] if len(sys.argv) > 1 else "."
SHIFT, CTRL, ALT, CMD = 1 << 17, 1 << 18, 1 << 19, 1 << 20
ax = collections.defaultdict(lambda: collections.defaultdict(list))   # top menu -> normalised title -> [(key, mods)]
top = None
def norm(t):
    t = re.sub(r"[“\"].*?[”\"]", "", t); t = t.replace("…", "").replace("...", "").strip().lower()
    return {"hide tab bar": "show tab bar", "hide preview": "show preview", "hide status bar": "show status bar", "use groups": "use stacks", "open enclosing folder in new window": "enclosing folder in new window", "select startup disk on desktop": "select startup disk", "settings": "preferences", "quicklook": "quick look", "move item here": "move items here", "copy  as pathname": "copy as pathname", "copy as pathname": "copy as pathname"}.get(re.sub(r"\s+", " ", t), re.sub(r"\s+", " ", t))
for line in open(f"{root}/docs/desktop/Finder.menu-ax-dump.tsv", encoding="utf-8"):
    f = line.rstrip("\n").split("\t")
    if len(f) < 4: continue
    d, title, key, mods = f[0], f[1], f[2], f[3]
    if d == "0": top = title; continue
    if top in (None, "Apple") or not title: continue
    if d != "1" and top not in ("View",): pass
    ax[top][norm(title)].append((key, int(mods) if mods.isdigit() else 0))
rows = []; top = None; prevkey = {}
for line in open(f"{root}/docs/desktop/Finder.menu-actions.txt", encoding="utf-8"):
    line = line.rstrip("\n")
    if not line.strip(): continue
    depth = (len(line) - len(line.lstrip(" "))) // 2
    f = line.strip(" ").split("\t") if line.strip(" ") else []
    title = line[depth * 2:].split("\t")[0]; action = line.split("\t")[1] if "\t" in line else ""; key = line.split("\t")[2] if line.count("\t") >= 2 else ""
    if depth == 0: top = title; rows.append((0, title, "", "", 0, 0)); continue
    if action == "(null)" and not title.strip(): rows.append((depth, "", "", "", 0, 0)); continue
    if title.strip() == "Item": continue
    mask = 0; k = key
    cand = ax.get(top, {}).get(norm(title)) or ax.get("Finder" if top == "Finder" else top, {}).get(norm(title))
    if cand:
        ck, mods = cand.pop(0) if len(cand) > 1 else cand[0]
        k = (ck.lower() if len(ck) == 1 else ck) if ck else k.lower() if k else ""
        mask = (0 if mods & 8 else CMD) | (SHIFT if mods & 1 else 0) | (ALT if mods & 2 else 0) | (CTRL if mods & 4 else 0)
        if not ck and key == "": mask = 0
    elif k:                                                              # not in the tree: a hidden alternate of the item before (option), or a plain command key
        dup = prevkey.get((top, depth)) == (title.strip(), k)
        if k.isupper() and len(k) == 1: mask = CMD | SHIFT; k = k.lower()
        else: mask = CMD | (ALT if dup else 0)
    else: mask = 0
    if title.strip() == "Hide Others": mask = CMD | ALT
    UP, DOWN = "\uf700", "\uf701"
    ov = {("Move to Trash", "cmdMoveToTrash:"): ("\x7f", CMD), ("Delete Immediately…", "cmdDeleteImmediately:"): ("\x7f", CMD | ALT), ("Enclosing Folder", "cmdOpenParent:"): (UP, CMD),
          ("Open Enclosing Folder in New Window", "cmdOpenParentAltBrowse:"): (UP, CMD | CTRL), ("Open Selection", "cmdOpenWithDownArrow:"): (DOWN, CMD), ("Open Selection", "cmdOpenWithOptionDownArrow:"): (DOWN, CMD | ALT)}
    if (title.strip(), action) in ov: k, mask = ov[(title.strip(), action)]
    prevkey[(top, depth)] = (title.strip(), key)
    rows.append((depth, title, action, k, mask, 0 if (cand or top == 'Finder' or title.strip() in ('Group By',)) else 1))
def c(s):
    out = ""
    for ch in s.replace("\x08", "\x7f"):                       # the delete key is 0x7f in the window server's key map (the nib has 0x08)
        for byte in ch.encode("utf-8"):
            out += chr(byte) if 0x20 <= byte < 0x7f and chr(byte) not in ("\"", "\\") else "\\%03o" % byte
    return '"' + out + '"'
with open(f"{root}/finder/src/TMenuFallback.inc", "w", encoding="utf-8") as o:
    o.write("/* generated by tools/gen_finder_menu.py: depth, title, action, key, modifier mask (NSEventModifierFlags) */\n")
    for d, t, a, k, m, h in rows:
        o.write("\t{ %d, %s, %s, %s, 0x%x, %d },\n" % (d, c(t), c("" if a == "(null)" else a), c(k), m, h))
print(len(rows), "rows")

