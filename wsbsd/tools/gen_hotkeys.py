#!/usr/bin/env python3
"""Writes src/sls_hotkey_defaults.c from docs/golden/hotkeys-macos26-runner.txt (lab/hotkeys.scen run on a macOS runner): the symbolic hot key table of a fresh session --
for every id 0..0x108 whether it has a value (GetSymbolicHotKeyValue: character code, key code, modifier mask) and whether it is enabled (IsSymbolicHotKeyEnabled)."""
import re,sys
vals={};en={};i32=0;i13=0
for l in open(sys.argv[1]):
    m=re.match(r'raw (32011|32013) reqsize=\d+ -> reply_id=\d+ bits=\w+ size=(\d+) hex=([0-9a-f]*)',l)
    if not m: continue
    b=bytes.fromhex(m[3]); rc=int.from_bytes(b[8:12],'little')
    if m[1]=='32011':
        vals[i32]=(rc,int.from_bytes(b[12:16],'little') if rc==0 else 0,int.from_bytes(b[16:20],'little') if rc==0 else 0,int.from_bytes(b[20:24],'little') if rc==0 else 0); i32+=1
    else:
        en[i13]=int.from_bytes(b[12:16],'little') if rc==0 else 0; i13+=1
print('/* Generated by tools/gen_hotkeys.py from docs/golden/hotkeys-macos26-runner.txt -- do not edit. */')
print('#include <stdint.h>')
print('typedef struct { uint8_t valid; uint16_t chr, keycode; uint32_t mods; uint8_t enabled; } sym_default;')
print('const sym_default sls_sym_defaults[0x109] = {')
for i in range(0x109):
    rc,a,b2,c=vals[i]
    print('\t[%d] = { %d, %d, %d, %d, %d },'%(i,1 if rc==0 else 0,a&0xffff,b2&0xffff,c,en.get(i,0) & 1))
print('};')
sys.stderr.write("%d valid values, %d enabled\n"%(sum(1 for v in vals.values() if v[0]==0),sum(en.values())))
