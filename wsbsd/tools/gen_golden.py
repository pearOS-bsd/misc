#!/usr/bin/env python3
"""Turns recorded real-WindowServer replies (docs/golden/*.txt: "id=.. reqsize=.. reply_id=.. bits=.. size=.. hex=..") into src/sls_golden.c:
a table of replies for header-only requests that have no dedicated handler. Port names in complex replies are zeroed (no Mach ports here)."""
import re,sys
rows=[]
for path in sys.argv[2:]:
    for l in open(path):
        m=re.match(r'id=(\d+) reqsize=(\d+) reply_id=(\d+) bits=([0-9a-f]+) size=(\d+) hex=([0-9a-f]*)',l)
        if not m: continue
        i,rq,rid,bits,size,hx=int(m[1]),int(m[2]),int(m[3]),int(m[4],16),int(m[5]),bytes.fromhex(m[6])
        if rq!=0x18 or 29000<=i<29042: continue
        hx=bytearray(hx)
        if bits&0x80000000 and len(hx)>=12:
            ndesc=int.from_bytes(hx[0:4],'little')
            for k in range(ndesc): hx[4+12*k:4+12*k+4]=b'\0\0\0\0'      # port names
        rows.append((i,bool(bits&0x80000000),size,bytes(hx)))
rows.sort()
out=['/* Generated by tools/gen_golden.py from docs/golden/*.txt -- do not edit. Replies recorded from the real WindowServer for header-only requests. */',
     '#include "wsd_priv.h"','#include <string.h>','',
     'typedef struct { int id; int complex; uint32_t size; uint32_t body_len; const uint8_t *body; } golden_reply;']
for i,c,s,b in rows:
    out.append('static const uint8_t g%d[] = {%s};'%(i,','.join(str(x) for x in b) if b else '0'))
out.append('static const golden_reply golden[] = {')
for i,c,s,b in rows: out.append('\t{ %d, %d, %d, %d, g%d },'%(i,int(c),s,len(b),i))
out.append('};')
out.append('''
/* Replies to header-only requests (0x18 bytes) with no dedicated handler: what the real server answers in a fresh session. Returns -2 if unknown. */
int sls_golden_reply(conn *c, const mach_msg_header_t *h)
{
	for (size_t i = 0; i < sizeof golden / sizeof golden[0]; i++) {
		if (golden[i].id != h->msgh_id) continue;
		uint8_t m[0x100]; memset(m, 0, sizeof m);
		fill_reply_header((mach_msg_header_t *)m, h, golden[i].size, golden[i].complex);
		memcpy(m + 0x18, golden[i].body, golden[i].body_len);
		struct iovec v = { m, golden[i].size };
		return ws_ipc_send(c->fd, &v, 1, NULL, 0);
	}
	return -2;
}
''')
open(sys.argv[1],'w').write('\n'.join(out)+'\n')
print(len(rows),'recorded replies')
