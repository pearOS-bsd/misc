#!/usr/bin/env python3
"""Writes src/sls_generic.c: for every SkyLight routine without a dedicated handler or a recorded reply, a wire-correct acceptor generated from the decompiled server routine
(request size, complex bit, descriptor count; reply size from docs/skylight-msgid-table.txt). The routine itself is not reproduced: it answers success (0) with a reply of the right size.
usage: gen_generic.py <corpus dir> <table> <ids file: one routine id per line> > src/sls_generic.c"""
import json,glob,re,sys
corpus,table,idsf=sys.argv[1:4]
items={}
for f in glob.glob(corpus+'/*.txt'):
    try: d=json.load(open(f))
    except: continue
    for it in d['normalized_result']['items']:
        if it.get('status')=='ok' and it.get('pseudocode'): items[it['procedure']['name']]=it['pseudocode']
rows={}
for l in open(table):
    if l.startswith('#') or not l.strip(): continue
    p=l.split(); rows[int(p[0])]=(p[1],int(p[2]),int(p[3],16))
ids=[int(x) for x in open(idsf).read().split() if x.isdigit()]
var=[]
out=['/* Generated by tools/gen_generic.py from the decompiled server routines -- do not edit. */','#include "wsd_priv.h"','#include <string.h>','',
'typedef struct { int id; uint32_t req_size; int complex; int ndesc; uint32_t reply_size; } gen_entry;','static const gen_entry gen_table[] = {']
n=0
cases=[]
for i in sorted(ids):
    name,argc,rmax=rows[i]; c=items.get('__X'+name[3:]) or items.get(name)
    if not c: continue
    sizes=re.findall(r'param_\\d\\[1\\]\\s*(?:==|!=)\\s*(0x[0-9a-fA-F]+|\\d+)',c.replace('\\\\','\\'))
    sizes=re.findall(r'param_\d\[1\]\s*(?:==|!=)\s*(0x[0-9a-fA-F]+|\d+)',c)
    cplx=1 if re.search(r'param_\d\[6\]\s*==\s*1',c) else 0
    if not sizes:
        var.append('\t{ %d, %d, %d, %d },   /* %s */'%(i,cplx,max(rmax,0x24),argc,name)); continue
    out.append('\t{ %d, %d, %d, %d, %d },   /* %s */'%(i,int(sizes[0],0),cplx,1 if cplx else 0,max(rmax,0x24),name))
    cases.append('%d %d %d %d'%(i,int(sizes[0],0),cplx,max(rmax,0x24)))
    n+=1
out.append('};')
out.append('typedef struct { int id; int complex; uint32_t reply_size; int argc; } gen_var_entry;')
out.append('static const gen_var_entry gen_var_table[] = {')
out.extend(var)
out.append('};')
out.append('''
int sls_generic_reply(conn *c, const uint8_t *buf, size_t len)
{
	const mach_msg_header_t *h = (const mach_msg_header_t *)buf;
	for (size_t i = 0; i < sizeof gen_table / sizeof *gen_table; i++) {
		const gen_entry *e = &gen_table[i];
		if ((uint32_t)e->id != (uint32_t)h->msgh_id) continue;
		int is_complex = (h->msgh_bits & MACH_MSGH_BITS_COMPLEX) != 0;
		if (is_complex != e->complex || h->msgh_size != e->req_size || len < h->msgh_size) return reply_simple(c->fd, h, -304);
		if (e->complex && rd32(buf, 0x18) != (uint32_t)e->ndesc) return reply_simple(c->fd, h, -304);
		if (e->reply_size <= 0x24) return reply_simple(c->fd, h, 0);
		uint8_t r[0x400]; uint32_t rs = e->reply_size > sizeof r ? (uint32_t)sizeof r : e->reply_size;
		memset(r, 0, sizeof r);
		fill_reply_header((mach_msg_header_t *)r, h, rs, 0);
		memcpy(r + 0x18, &WS_NDR, sizeof WS_NDR);
		return ws_ipc_send(c->fd, &(struct iovec){ r, rs }, 1, NULL, 0);
	}
	for (size_t i = 0; i < sizeof gen_var_table / sizeof *gen_var_table; i++) {        /* variable-size requests: the size is only bounded here (0x20 .. 0x4100) */
		const gen_var_entry *e = &gen_var_table[i];
		if ((uint32_t)e->id != (uint32_t)h->msgh_id) continue;
		int is_complex = (h->msgh_bits & MACH_MSGH_BITS_COMPLEX) != 0;
		if (is_complex != e->complex || h->msgh_size < 0x18 || h->msgh_size > 0x4100 || len < h->msgh_size) return reply_simple(c->fd, h, -304);
		if (e->reply_size <= 0x24) return reply_simple(c->fd, h, 0);
		uint8_t r[0x400]; uint32_t rs = e->reply_size > sizeof r ? (uint32_t)sizeof r : e->reply_size;
		memset(r, 0, sizeof r);
		fill_reply_header((mach_msg_header_t *)r, h, rs, 0);
		memcpy(r + 0x18, &WS_NDR, sizeof WS_NDR);
		return ws_ipc_send(c->fd, &(struct iovec){ r, rs }, 1, NULL, 0);
	}
	return -2;
}
''')
sys.stdout.write('\n'.join(out)+'\n')
open('test/generic_cases.txt','w').write('# id request_size complex reply_size (exact-size acceptors of src/sls_generic.c)\n'+'\n'.join(cases)+'\n')
sys.stderr.write("%d acceptors\n"%n)
