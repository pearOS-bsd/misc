#!/usr/bin/env python3
"""genprops.py: reads layerprops.spec and writes src/CALayerProps.inc: the data struct and the property table of the layers, and the typed accessors (one macro per class)."""
import os
here = os.path.dirname(os.path.abspath(__file__))
ctype = {'F': 'float', 'D': 'CGFloat', 'B': 'BOOL', 'U': 'unsigned', 'UL': 'NSUInteger', 'PT': 'CGPoint', 'SZ': 'CGSize', 'RC': 'CGRect', 'TF': 'CATransform3D', 'COL': 'CGColorRef', 'PATH': 'CGPathRef', 'OBJ': 'id', 'STR': 'NSString *', 'ARR': 'NSArray *'}
store = {'F': 'float', 'D': 'CGFloat', 'B': 'BOOL', 'U': 'unsigned', 'UL': 'NSUInteger', 'PT': 'CGPoint', 'SZ': 'CGSize', 'RC': 'CGRect', 'TF': 'CATransform3D', 'COL': 'CGColorRef', 'PATH': 'CGPathRef', 'OBJ': '__unsafe_unretained id', 'STR': '__unsafe_unretained id', 'ARR': '__unsafe_unretained id'}
isget = {'hidden', 'doubleSided', 'geometryFlipped', 'opaque', 'wrapped'}
rows = []; cls = 'CALayer'
for l in open(os.path.join(here, 'layerprops.spec')):
    l = l.split('#')[0].rstrip()
    if not l.strip(): continue
    if l.startswith('@'): cls = l[1:].strip(); continue
    p = l.split(None, 3)
    name, typ, dflt = p[0], p[1], p[2]
    flags = p[3].strip() if len(p) > 3 else ''
    tt, _, over = typ.partition(':')
    rows.append((name, tt, dflt, flags, cls, over))
def cap(n): return n[0].upper() + n[1:]
def init_expr(t, d):
    if t in ('PT', 'SZ'): return '(%s){ %s, %s }' % (ctype[t], *d.strip('{}').split(','))
    if t == 'RC': return '(CGRect){ { %s, %s }, { %s, %s } }' % tuple(d.strip('{}').split(','))
    return d
o = ['/* generated by tools/genprops.py from tools/layerprops.spec: do not edit */\n', 'typedef struct CALayerData {\n']
for n, t, d, f, c, ov in rows: o.append('\t%s %s;\n' % (store[t], n))
o.append('} CALayerData;\n\nenum { %s, CAPropCount };\n\n' % ', '.join('CAP_' + n for n, *_ in rows))
o.append('static const CAPropDesc kCAProps[] = {\n')
for n, t, d, f, c, ov in rows:
    fl = ['CAF_' + x for x in f.replace(' ', '').split(',') if x]
    o.append('\t{ "%s", CAT_%s, offsetof(CALayerData, %s), %s, "%s" },\n' % (n, t, n, ' | '.join(fl) if fl else '0', c))
o.append('};\n\nstatic void CALayerDataInit(CALayerData *d)\n{\n\tmemset(d, 0, sizeof *d);\n')
for n, t, d, f, c, ov in rows:
    if t == 'COL':
        if d == 'BLACK': o.append('\td->%s = (CGColorRef)CFRetain(CALayerBlackColor());\n' % n)
        elif d == 'WHITE': o.append('\td->%s = (CGColorRef)CFRetain(CALayerWhiteColor());\n' % n)
    elif t in ('STR', 'OBJ', 'ARR'):
        if d not in ('nil',): o.append('\td->%s = %s;\n' % (n, d))
    elif t == 'PATH': pass
    elif t == 'TF': o.append('\td->%s = CATransform3DIdentity;\n' % n)
    else: o.append('\td->%s = %s;\n' % (n, init_expr(t, d)))
o.append('}\n\n')
for c in dict.fromkeys(r[4] for r in rows):
    o.append('#define CA_ACCESSORS_%s \\\n' % c)
    for n, t, d, f, cc, ov in rows:
        if cc != c: continue
        ct = ov or ctype[t]
        g = ('is' + cap(n)) if n in isget else n
        if ov == 'CFTypeRef':
            o.append('- (CFTypeRef)%s { return (__bridge CFTypeRef)CAGetObjProp(self, CAP_%s); } \\\n- (void)set%s:(CFTypeRef)v { CASetObjProp(self, CAP_%s, (__bridge id)v); } \\\n' % (g, n, cap(n), n))
        elif t in ('STR', 'ARR', 'OBJ'):
            o.append('- (%s)%s { return (%s)CAGetObjProp(self, CAP_%s); } \\\n- (void)set%s:(%s)v { CASetObjProp(self, CAP_%s, v); } \\\n' % (ct, g, ct, n, cap(n), ct, n))
        else:
            o.append('- (%s)%s { %s v; CAGetProp(self, CAP_%s, &v); return v; } \\\n- (void)set%s:(%s)v { %s s = (%s)v; CASetProp(self, CAP_%s, &s); } \\\n' % (ct, g, store[t], n, cap(n), ct, store[t], store[t], n) if ov else
                     '- (%s)%s { %s v; CAGetProp(self, CAP_%s, &v); return v; } \\\n- (void)set%s:(%s)v { CASetProp(self, CAP_%s, &v); } \\\n' % (ct, g, ct, n, cap(n), ct, n))
    o.append('\n')
open(os.path.join(here, '..', 'src', 'CALayerProps.inc'), 'w').write(''.join(o))
print(len(rows), 'properties')
