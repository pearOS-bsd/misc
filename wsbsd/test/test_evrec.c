static void same(const char *tag, const uint8_t *want, size_t n, const uint8_t *got, size_t gn)
{
	if (gn != n || memcmp(want, got, n)) {
		size_t i = 0; while (i < n && i < gn && want[i] == got[i]) i++;
		printf("builder mismatch: %s (len %zu want %zu, first difference at byte %zu)\n", tag, gn, n, i);
		fails++;
	}
}

int main(void)
{
	ws_evrec r; float x, y;
	CHECK(ws_evrec_parse(mouse_moved, sizeof mouse_moved, &r) == 0);
	CHECK(ws_evrec_type(&r) == 5 && ws_evrec_location(&r, &x, &y) == 0 && x == 100.0f && y == 200.0f && ws_evrec_flags(&r) == 0x100 && ws_evrec_timestamp(&r) == TS);
	CHECK(ws_evrec_parse(left_down, sizeof left_down, &r) == 0 && ws_evrec_type(&r) == 1 && ws_evrec_click_state(&r) == 1);
	CHECK(ws_evrec_parse(left_down_shift, sizeof left_down_shift, &r) == 0 && ws_evrec_type(&r) == 1 && ws_evrec_click_state(&r) == 2 && ws_evrec_flags(&r) == 0x20000);
	CHECK(ws_evrec_location(&r, &x, &y) == 0 && x == 300.5f && y == 400.25f);
	CHECK(ws_evrec_parse(key_down, sizeof key_down, &r) == 0 && ws_evrec_type(&r) == 10 && ws_evrec_keycode(&r) == 36 && ws_evrec_flags(&r) == 0x20000100);
	CHECK(ws_evrec_parse(key_up, sizeof key_up, &r) == 0 && ws_evrec_type(&r) == 11 && ws_evrec_keycode(&r) == 0);
	CHECK(ws_evrec_parse(scroll, sizeof scroll, &r) == 0 && ws_evrec_type(&r) == 22);

	uint8_t out[512]; size_t n;
	n = ws_evrec_make_mouse(out, sizeof out, 5, 100, 200, 0x100, 0, 0, TS);               same("mouse moved", mouse_moved, sizeof mouse_moved, out, n);
	n = ws_evrec_make_mouse(out, sizeof out, 1, 100, 200, 0x100, 1, 0, TS);               same("left down", left_down, sizeof left_down, out, n);
	n = ws_evrec_make_mouse(out, sizeof out, 1, 300.5f, 400.25f, 0x20000, 2, 0, TS);      same("left down shift", left_down_shift, sizeof left_down_shift, out, n);
	{
		float kx, ky; uint32_t bx = 0x450c29b0, by = 0x44095680; memcpy(&kx, &bx, 4); memcpy(&ky, &by, 4);
		n = ws_evrec_make_key(out, sizeof out, 1, 36, 0x20000100, kx, ky, TS, 0x0d, 0x0a); same("key down", key_down, sizeof key_down, out, n);
		n = ws_evrec_make_key(out, sizeof out, 0, 0, 0x20000100, kx, ky, TS, 0x61, 0x0a);  same("key up", key_up, sizeof key_up, out, n);
	}
	/* malformed input is rejected */
	CHECK(ws_evrec_parse(mouse_moved, sizeof mouse_moved - 4, &r) < 0);                       /* truncated value */
	CHECK(ws_evrec_parse(mouse_moved, 3, &r) < 0);
	{ uint8_t bad[sizeof mouse_moved]; memcpy(bad, mouse_moved, sizeof bad); bad[3] = 3; CHECK(ws_evrec_parse(bad, sizeof bad, &r) < 0); }   /* wrong leading word */
	{ uint8_t bad[sizeof mouse_moved]; memcpy(bad, mouse_moved, sizeof bad); bad[5] = 7; CHECK(ws_evrec_parse(bad, sizeof bad, &r) < 0); }   /* unknown value kind */
	CHECK(ws_evrec_make_mouse(out, 20, 5, 0, 0, 0, 0, 0, TS) == 0);                           /* buffer too small */
	printf(fails ? "%d failures\n" : "event record tests passed (all golden vectors match)\n", fails);
	return fails != 0;
}
