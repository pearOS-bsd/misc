#!/usr/bin/env python3
"""Turns the accessibility dump of the real TextEdit's menu bar (tools/TextEdit.menu-ax-dump.txt, from the Mac: `mb com.apple.TextEdit`) into src/TEMenu.inc:
a flat list of  { depth, title, key, mask, enabled }  rows (depth -1 starts a top-level menu). The AX modifier bits: 1 shift, 2 option, 4 control, 8 no command."""
import re, sys
rows = []; skip_apple = False; in_recent = False
for line in open(sys.argv[1], encoding='utf-8'):
    line = line.rstrip('\n')
    if line.startswith('## '):
        skip_apple = line[3:] == 'Apple'; in_recent = False
        if not skip_apple: rows.append((-1, line[3:], '', 0, 1))
        continue
    if skip_apple: continue
    m = re.match(r'^( *)(.*)$', line); depth = len(m.group(1)) // 2; t = m.group(2); en = 1
    if t.endswith(' (disabled)'): t = t[:-11]; en = 0
    key = ''; mask = 0x100000
    k = re.match(r'^(.*) \[(.+) m(\d+)\]$', t)
    if k:
        t = k.group(1); key = k.group(2); mod = int(k.group(3)); mask = (0x100000 if not mod & 8 else 0) | (0x20000 if mod & 1 else 0) | (0x80000 if mod & 2 else 0) | (0x40000 if mod & 4 else 0)
    if t == '--': t = '-'
    if t.startswith('<<'): continue
    if depth == 0: in_recent = (t == 'Open Recent')
    if depth == 1 and in_recent and t != 'Clear Menu' and t != '-': continue       # the recent documents are the user's own
    if t == 'Untitled' and depth == 0: continue       # the window list
    rows.append((depth, t, key, mask, en))
out = ['/* generated by tools/gen_menu.py from the Mac\'s TextEdit menu bar (accessibility dump): do not edit */']
for d, t, key, mask, en in rows:
    esc = lambda s: s.replace('\\', '\\\\').replace('"', '\\"')
    out.append('{ %d, @"%s", @"%s", 0x%x, %d },' % (d, esc(t), esc(key), mask, en))
open(sys.argv[2], 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(len(rows), 'rows')
