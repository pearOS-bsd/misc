#!/usr/bin/env python3
"""Reads the window settings that Terminal.app ships (Contents/Resources/Initial Settings/*.terminal, keyed archives of NSColor / NSFont) and writes src/Profiles.inc: the numbers of every profile
(colours as r g b a, the 16 ANSI colours, font name and size, blur, window size, cursor and bold options). Only values are taken; no code or artwork.
usage: gen_profiles.py [Terminal.app]  > src/Profiles.inc"""
import plistlib, glob, os, sys
app = sys.argv[1] if len(sys.argv) > 1 else "/System/Applications/Utilities/Terminal.app"
res = os.path.join(app, "Contents/Resources/Initial Settings")
def U(o, objs): return objs[o.data] if isinstance(o, plistlib.UID) else o
def color(b):
    a = plistlib.loads(b); objs = a["$objects"]; top = objs[a["$top"]["root"].data]; d = {k: U(v, objs) for k, v in top.items()}
    if "NSRGB" in d:
        p = [float(x) for x in d["NSRGB"].split(b"\x00")[0].decode().split()]; return (p[0], p[1], p[2], p[3] if len(p) > 3 else 1.0)
    if "NSWhite" in d:
        p = [float(x) for x in d["NSWhite"].split(b"\x00")[0].decode().split()]; return (p[0], p[0], p[0], p[1] if len(p) > 1 else 1.0)
    return None
def font(b):
    a = plistlib.loads(b); objs = a["$objects"]; top = objs[a["$top"]["root"].data]
    sz = U(top.get("NSSize"), objs); return (U(top["NSName"], objs), float(sz) if sz is not None else 12.0)
ANSI = ["Black", "Red", "Green", "Yellow", "Blue", "Magenta", "Cyan", "White"]
def c(v): return "{ %.5f, %.5f, %.5f, %.5f }" % v if v else "{ -1, -1, -1, -1 }"
print("/* generated by tools/gen_profiles.py from the Terminal.app on the author's Mac: values only */")
names = []
for f in sorted(glob.glob(os.path.join(res, "*.terminal"))):
    s = plistlib.load(open(f, "rb")); n = s["name"]; names.append(n)
    g = lambda k: color(s[k]) if k in s else None
    ansi = [g("ANSI%sColor" % a) for a in ANSI] + [g("ANSIBright%sColor" % a) for a in ANSI]
    fn, fs = font(s["Font"]) if "Font" in s else ("SFMonoTerminal-Regular", 11.0)
    print('	{ "%s", %s, %s, %s, %s, %s, "%s", %.1f, %.5f, %.3f, %d, %d, %d, %d,' % (n, c(g("BackgroundColor")), c(g("TextColor")), c(g("TextBoldColor")), c(g("CursorColor")), c(g("SelectionColor")), fn, fs,
          s.get("FontWidthSpacing", 1.0), float(s.get("BackgroundBlur", 0.0)), int(s.get("columnCount", 80)), int(s.get("rowCount", 24)), int(bool(s.get("CursorBlink", False))), int(bool(s.get("FontAntialias", True)))))
    print("	  { %s } }," % ", ".join(c(x) for x in ansi))
